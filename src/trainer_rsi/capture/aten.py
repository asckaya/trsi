PARAMETER_KINDS: frozenset[str] = frozenset({"parameter", "buffer", "constant_tensor"})


def kind_of(target: str) -> Kind:
    """Which cost rule applies to a captured target, or ``other`` if none does.

    An op nobody wrote a rule for is reported as unpriced rather than guessed
    at: a guessed shape understates the floor and makes the step look worse than
    it is.
    """
    parts = target.split(".")
    name = parts[1] if parts[0] in ("aten", "torch") and len(parts) > 1 else target
    return OP_KINDS.get(name, "other")
